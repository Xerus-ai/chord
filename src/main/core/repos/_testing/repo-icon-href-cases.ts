function readCandidates(href: string, sourceFile: string): unknown {
  try {
    return declaredIconHrefCandidates(href, sourceFile);
  } catch (error) {
    return `throws ${String(error)}`;
  }
}

export function collectDeclaredHrefRecord() {
  return {
    extract: Object.fromEntries(
      Object.entries(SOURCES).map(([name, source]) => [name, extractDeclaredIconHref(source)])
    ),
    candidates: Object.fromEntries(
      SOURCE_FILES.map((sourceFile) => [
        sourceFile,
        Object.fromEntries(HREFS.map((href) => [href, readCandidates(href, sourceFile)])),
      ])
    ),
  };
}
